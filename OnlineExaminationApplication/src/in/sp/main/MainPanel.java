   private void loadQuestion() {

    jLabel22.setText(
        "<html>Q" + (currentQuestion + 1) + ". "
        + questions[currentQuestion]
        + "</html>"
    );

    jRadioButton1.setText(options[currentQuestion][0]);
    jRadioButton2.setText(options[currentQuestion][1]);
    jRadioButton3.setText(options[currentQuestion][2]);
    jRadioButton4.setText(options[currentQuestion][3]);

    jLabel24.setText(
        "Question " + (currentQuestion + 1)
        + " of " + questions.length
    );

    buttonGroup1.clearSelection();

    if (userAnswers[currentQuestion] == 0) {
        jRadioButton1.setSelected(true);
    }
    else if (userAnswers[currentQuestion] == 1) {
        jRadioButton2.setSelected(true);
    }
    else if (userAnswers[currentQuestion] == 2) {
        jRadioButton3.setSelected(true);
    }
    else if (userAnswers[currentQuestion] == 3) {
        jRadioButton4.setSelected(true);
    }

    jLabel6.setVisible(currentQuestion > 0);
    jLabel7.setVisible(currentQuestion < questions.length - 1);
}
   private void saveCurrentAnswer() {

    if (jRadioButton1.isSelected()) {
        userAnswers[currentQuestion] = 0;
    }
    else if (jRadioButton2.isSelected()) {
        userAnswers[currentQuestion] = 1;
    }
    else if (jRadioButton3.isSelected()) {
        userAnswers[currentQuestion] = 2;
    }
    else if (jRadioButton4.isSelected()) {
        userAnswers[currentQuestion] = 3;
    }
}
private void startExamTimer() {

    if (examTimer != null && examTimer.isRunning()) {
        examTimer.stop();
    }

    remainingSeconds = 30 * 60;

    updateTimerLabel();

    examTimer = new javax.swing.Timer(
        1000,
        e -> {

            remainingSeconds--;

            updateTimerLabel();

            if (remainingSeconds <= 0) {

                examTimer.stop();

                JOptionPane.showMessageDialog(
                    this,
                    "Time is over!\nYour exam will be submitted automatically.",
                    "Time Up",
                    JOptionPane.INFORMATION_MESSAGE
                );

                submitExam();
            }
        }
    );

    examTimer.start();
}
private void updateTimerLabel() {

    int minutes = remainingSeconds / 60;
    int seconds = remainingSeconds % 60;

    jLabel21.setText(
        "Time : " + String.format("%02d:%02d", minutes, seconds)
    );
}

private void submitExam() {

    if (examTimer != null && examTimer.isRunning()) {
        examTimer.stop();
    }

    saveCurrentAnswer();

    score = 0;

    for (int i = 0; i < questions.length; i++) {

        if (userAnswers[i] == correctAnswers[i]) {
            score++;
        }
    }

    long endTime = System.currentTimeMillis();

    long timeTakenSeconds =
            (endTime - examStartTime) / 1000;

    long minutes = timeTakenSeconds / 60;
    long seconds = timeTakenSeconds % 60;

    jLabel26.setText(
        "Congratulations, " + loggedInUserName
    );

    jLabel27.setText("Score");

    jLabel28.setText(
        score + " / " + questions.length
    );

    jLabel29.setText(
        "Time Taken : "
        + minutes + " minutes "
        + seconds + " seconds"
    );

    jLabel30.setText(
        "<html>"
        + "Correct Answers : " + score
        + "<br>"
        + "Incorrect Answers : "
        + (questions.length - score)
        + "<br>"
        + "Total Questions : " + questions.length
        + "</html>"
    );

    showPanel("RESULT");
}
