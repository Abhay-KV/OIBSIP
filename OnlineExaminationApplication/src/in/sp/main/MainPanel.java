    private void jLabel5MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel5MouseClicked
        // TODO add your handling code here:
        String email = jTextField1.getText().trim();
    String password = new String(jPasswordField1.getPassword());

    if (email.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter email and password"
        );
        return;
    }

    String sql = "SELECT id, name FROM student WHERE email=? AND password=?";

    try (
        Connection con = DBConnection.getConnection();
        PreparedStatement ps = con.prepareStatement(sql)
    ) {

        ps.setString(1, email);
        ps.setString(2, password);

        try (ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {

                // Save logged-in student information
                loggedInUserId = rs.getInt("id");
                loggedInUserName = rs.getString("name");

                JOptionPane.showMessageDialog(
                        this,
                        "Login Successful!\nWelcome " + loggedInUserName
                );

                // Go to Profile
                showPanel("PROFILE");

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Invalid email or password",
                        "Login Failed",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_jLabel5MouseClicked

    private void jLabel12MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel12MouseClicked
        // TODO add your handling code here:
        
        String name = jTextField2.getText().trim();
    String email = jTextField3.getText().trim();
    String pass = jTextField4.getText().trim();
    String phone = jTextField5.getText().trim();

    // Check empty fields
    if (name.isEmpty() || email.isEmpty() || pass.isEmpty() || phone.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "All fields are required!",
            "Registration Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Check phone number
    if (!phone.matches("\\d{10}")) {
        JOptionPane.showMessageDialog(
            this,
            "Phone number must contain exactly 10 digits!",
            "Registration Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String sql = "INSERT INTO student (name, email, password, phone) "
               + "VALUES (?, ?, ?, ?)";

    try (
        Connection con = DBConnection.getConnection();
        PreparedStatement ps = con.prepareStatement(sql)
    ) {

        ps.setString(1, name);
        ps.setString(2, email);
        ps.setString(3, pass);
        ps.setString(4, phone);

        int rows = ps.executeUpdate();

        if (rows > 0) {

            JOptionPane.showMessageDialog(
                this,
                "Student Registration Successful!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );

            // Clear registration fields
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");

            // Go back to Login
            cardLayout.show(jPanel1, "LOGIN");
        }

    } catch (SQLIntegrityConstraintViolationException e) {

        JOptionPane.showMessageDialog(
            this,
            "Email already exists!",
            "Registration Error",
            JOptionPane.ERROR_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_jLabel12MouseClicked

